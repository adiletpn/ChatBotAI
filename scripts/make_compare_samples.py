def render(html: str) -> bytes:
    folder, regular, bold = _font_dir()
    story = pymupdf.Story(html=html, user_css=CSS.format(regular=regular, bold=bold), archive=pymupdf.Archive(folder))
    buf = io.BytesIO()
    writer = pymupdf.DocumentWriter(buf)
    page = pymupdf.paper_rect("a4")
    more = True
    while more:
        device = writer.begin_page(page)
        more, _ = story.place(page + (60, 56, -60, -56))
        story.draw(device)
        writer.end_page()
    writer.close()
    return buf.getvalue()


def with_metadata(pdf_bytes: bytes, **meta) -> bytes:
    doc = pymupdf.open(stream=pdf_bytes, filetype="pdf")
    doc.set_metadata({**doc.metadata, "title": "Договор № 47/2026", "author": "ТОО «Демо-Завод»",
                      "creator": "Microsoft Word", "producer": "Microsoft Word", **meta})
    out = doc.tobytes(garbage=3, deflate=True)
    doc.close()
    return out


def main() -> None:
    original = with_metadata(render(ORIGINAL), creationDate=CREATED, modDate=CREATED)

    forged_html = ORIGINAL
    for old, new in FORGERIES:
        assert old in forged_html, old
        forged_html = forged_html.replace(old, new)
    forged = with_metadata(render(forged_html), creationDate=CREATED, modDate=CREATED)
    # как у настоящей подделки: правка дописана поверх файла, дата изменения — поздно вечером
    path = ROOT / "samples" / "Dogovor_47_prislannyi.pdf"
    path.write_bytes(forged)
    doc = pymupdf.open(path)
    doc.set_metadata({**doc.metadata, "modDate": "D:20261110234700+05'00'"})
    doc.saveIncr()
    doc.close()

    (ROOT / "samples" / "Dogovor_47_original.pdf").write_bytes(original)
    print("samples/Dogovor_47_original.pdf  — оригинал")
    print("samples/Dogovor_47_prislannyi.pdf — присланная копия с подделками")


if __name__ == "__main__":
    main()

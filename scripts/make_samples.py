def text_pdf(path: Path, text: str) -> None:
    doc = pymupdf.open()
    rect = pymupdf.paper_rect("a4")
    box = rect + (60, 60, -60, -60)
    paragraphs = text.split("\n")
    while paragraphs:
        page = doc.new_page(width=rect.width, height=rect.height)
        page.insert_font(fontname="F0", fontfile=FONT)
        y = box.y0
        while paragraphs:
            para = paragraphs[0]
            if not para.strip():
                paragraphs.pop(0)
                y += 8
                continue
            bold_like = para[:2].rstrip(".").isdigit() and len(para) < 70 or para.startswith("«")
            size = 13 if bold_like else 11.5
            # оцениваем высоту абзаца
            frame = pymupdf.Rect(box.x0, y, box.x1, box.y1)
            rc = page.insert_textbox(frame, para, fontname="F0", fontsize=size, align=pymupdf.TEXT_ALIGN_JUSTIFY)
            if rc < 0:  # не влезло — на новую страницу
                break
            used = (box.y1 - y) - rc
            y += used + 6
            paragraphs.pop(0)
        page.insert_text((rect.width / 2 - 4, rect.height - 30), str(len(doc)), fontname="F0", fontsize=9)
    doc.save(path)


def scan_pdf(path: Path, text: str) -> None:
    """Рисуем текст на странице, растеризуем в картинку и кладём в PDF без текстового слоя — как сканер."""
    src = pymupdf.open()
    page = src.new_page(width=595, height=842)
    page.insert_font(fontname="F0", fontfile=FONT)
    page.insert_textbox(pymupdf.Rect(70, 80, 530, 800), text, fontname="F0", fontsize=14, lineheight=1.5)
    pix = page.get_pixmap(dpi=200, colorspace=pymupdf.csGRAY)
    out = pymupdf.open()
    scan_page = out.new_page(width=595, height=842)
    scan_page.insert_image(scan_page.rect, stream=pix.tobytes("jpeg", jpg_quality=75))
    out.save(path)


